import assert from 'node:assert/strict';
import {openWorkspaceFind} from './workspace-header-actions.mjs';
import { join } from 'node:path';
import { evaluateApplication } from './application-inspector.mjs';

/** Compare reviewed component metrics while exercising the actual document commands. */
export async function runBlueComponentChecks({ page, app, artifacts }) {
  const checks = [];
  const check = (name, value) => { assert.equal(value, true, name); checks.push(name); };
  const plain = 'alpha beta gamma';
  await page.setViewport({ width: 1280, height: 860 });
  await app.loadMarkdown(plain, { layout: 'hybrid', selection: 0 }); await app.waitForIdle();
  await page.click('#editor .cm-line');
  await page.pressKey('Home', { modifiers: 2, code: 'Home' });
  await page.pressKey('End', { modifiers: 8, code: 'End' });
  await page.waitFor(() => document.querySelector('.format-group').classList.contains('has-selection'));
  await page.click('#text-color-button');
  await page.waitFor(() => document.getElementById('text-color-menu').classList.contains('show'));
  check('palette fills 232px with five equal columns and 2px gaps', await page.evaluate("(()=>{const p=document.getElementById('text-color-menu'),g=p.querySelector('.color-swatches'),s=[...g.children].map(e=>e.getBoundingClientRect()),r=p.getBoundingClientRect(),c=getComputedStyle(g);return r.width===232&&r.height===232&&s.length===10&&c.columnGap==='2px'&&s.every(x=>Math.abs(x.width-s[0].width)<.02)&&Math.abs(s[4].right-s[0].left-200)<1;})()"));
  check('palette actions share outlined/primary 96x32 geometry', await page.evaluate("(()=>{const a=[...document.querySelectorAll('#text-color-menu .color-menu-actions button')];return a.length===2&&a.every(e=>{const r=e.getBoundingClientRect(),s=getComputedStyle(e);return r.width===96&&r.height===32&&s.borderWidth==='1px';});})()"));
  await page.waitFor(() => getComputedStyle(document.getElementById('text-color-menu')).opacity === '1');
  const swatch = await page.waitForElementStable('#text-color-menu [data-inline-color="#dc2626"]');
  const point = {x:swatch.x+swatch.width/2,y:swatch.y+swatch.height/2,button:'left',clickCount:1};
  await page.connection.send('Input.dispatchMouseEvent', {type:'mousePressed',buttons:1,...point});
  await page.evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  await page.connection.send('Input.dispatchMouseEvent', {type:'mouseReleased',buttons:0,...point});
  check('color selection survives animation frames between pointer down and up', await page.evaluate("document.querySelector('#text-color-menu [data-inline-color=\"#dc2626\"]').getAttribute('aria-pressed')==='true'&&document.getElementById('text-color-menu').classList.contains('show')"));
  assert.equal(await app.getEditorValue(), plain); checks.push('swatches are pending until Apply');
  await page.screenshot(join(artifacts, 'blue-text-palette.png'));
  await page.click('#text-color-menu [data-inline-color-apply]');
  check('Apply writes the actual selected document range', (await app.getEditorValue()).includes('#dc2626'));
  await page.pressKey('z', { modifiers: 2, code: 'KeyZ' });
  assert.equal(await app.getEditorValue(), plain); checks.push('color formatting is undoable');
  await openWorkspaceFind(page);
  await page.fill('#find-input', '[');
  await page.click('.writing-find-options button:nth-child(3)');
  await page.waitFor(() => document.getElementById('find-input').getAttribute('aria-invalid') === 'true');
  check('invalid regex is a real validation state', await page.evaluate("document.querySelector('.writing-find-error').textContent.includes('表达式无效')&&document.querySelector('[data-find-action=replace-all]').disabled"));
  await page.screenshot(join(artifacts, 'blue-invalid-regex.png'));
  await page.click('[data-find-action=close]');
  await page.click('[data-menu-toggle="insert-menu"]');
  await page.click('#insert-menu [data-editor-action="open-link"]');
  check('link form uses its 384x188 compact contract', await page.evaluate("(()=>{const r=document.querySelector('#link-modal .modal').getBoundingClientRect();return r.width===384&&r.height===188;})()"));
  await page.pressKey('Escape');
  await page.setViewport({ width: 600, height: 480 });
  await page.click('#editor .cm-line');
  await page.pressKey('Home', { modifiers: 2, code: 'Home' });
  await page.pressKey('End', { modifiers: 8, code: 'End' });
  await page.waitFor(() => document.querySelector('.format-group').classList.contains('has-selection'));
  const savedSelection = await evaluateApplication(page, 'editorApi.getSelection()');
  assert.ok(savedSelection.start < savedSelection.end);
  await page.click('[data-menu-toggle="insert-menu"]');
  await page.waitFor(() => !document.querySelector('.format-group').classList.contains('has-selection'));
  assert.deepEqual(await evaluateApplication(page, 'editorApi.getSelection()'), savedSelection);
  checks.push('open application menus hide selection tools without losing the source selection');
  await page.click('[data-menu-toggle="insert-menu"]');
  await page.waitFor(() => document.querySelector('.format-group').classList.contains('has-selection'));
  checks.push('closing the menu restores the still-valid selection toolbar');
  await page.click('[data-menu-toggle="insert-menu"]');
  await page.click('#insert-menu [data-editor-action="open-image"]');
  check('image form remains bounded in the shortest native size', await page.evaluate("(()=>{const r=document.querySelector('#image-modal .modal').getBoundingClientRect();return r.width===400&&r.height<=340&&r.top>=16&&r.bottom<=innerHeight-16;})()"));
  await page.screenshot(join(artifacts, 'blue-image-600x480.png'));
  await page.pressKey('Escape');
  await page.setViewport({ width: 1280, height: 860 });
  return checks;
}
